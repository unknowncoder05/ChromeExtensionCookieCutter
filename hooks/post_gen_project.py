#!/usr/bin/env python3
"""Post-generation hook for ChromeExtensionCookieCutter."""
import os
import subprocess

IGNORE_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", "build", "dist"}
IGNORE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".ico", ".woff", ".woff2", ".ttf", ".eot"}

REPLACEMENTS = {
    "My Chrome Extension": "{{ cookiecutter.project_name }}",
    "my_chrome_extension": "{{ cookiecutter.project_slug }}",
    "my-chrome-extension": "{{ cookiecutter.project_slug_dashed }}",
    "PM Extension": "{{ cookiecutter.extension_short_name }}",
    "A general-purpose Chrome extension generated by ProjectMaker.": "{{ cookiecutter.extension_description }}",
    "Your Name": "{{ cookiecutter.author_name }}",
    "your@email.com": "{{ cookiecutter.author_email }}",
    "https://example.com": "{{ cookiecutter.homepage_url }}",
}


def replace_project_references():
    project_dir = os.getcwd()
    for root, dirs, files in os.walk(project_dir):
        dirs[:] = [directory for directory in dirs if directory not in IGNORE_DIRS]
        for filename in files:
            _, ext = os.path.splitext(filename)
            if ext in IGNORE_EXTENSIONS:
                continue
            filepath = os.path.join(root, filename)
            try:
                with open(filepath, "r", encoding="utf-8") as handle:
                    content = handle.read()
            except (UnicodeDecodeError, PermissionError):
                continue

            new_content = content
            for placeholder, value in REPLACEMENTS.items():
                new_content = new_content.replace(placeholder, value)

            if new_content != content:
                with open(filepath, "w", encoding="utf-8") as handle:
                    handle.write(new_content)


def init_git_repo():
    for cmd in [
        ["git", "init"],
        ["git", "add", "."],
        ["git", "commit", "-m", "Initial commit from ChromeExtensionCookieCutter"],
    ]:
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            print(f"Warning: '{' '.join(cmd)}' exited with code {result.returncode}")
            print(result.stderr)


def print_next_steps():
    slug = "{{ cookiecutter.project_slug }}"
    print(
        "\nChrome extension generated successfully.\n\n"
        f"  cd {slug}\n"
        "  npm install\n"
        "  npm run validate\n"
        "  npm run build\n\n"
        "Then load the dist/ directory from chrome://extensions in Developer mode.\n"
    )


if __name__ == "__main__":
    replace_project_references()
    init_git_repo()
    print_next_steps()
